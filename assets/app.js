  function rankDrugs(field, q) {
    const s = q.trim().toLowerCase();
    if (!s) return [];
    const out = [];
    for (const d of drugs) {
      let score = 0;
      if (field === 'name') {
        if (d.lower === s) score = 100;
        else if (d.synLower.indexOf(s) >= 0) score = 96;
        else if (d.lower.startsWith(s)) score = 84;
        else if (d.lower.includes(s)) score = 66;
        else if (s.length >= 4 && d.synLower.some(x => x.startsWith(s))) score = 60;
        else if (s.length >= 5 && d.synLower.some(x => x.includes(s))) score = 48;
      } else if (field === 'drugbank') {
        const v = d.id.toLowerCase();
        if (v === s) score = 100;
        else if (v.includes(s) && s.length >= 3) score = 70;
      } else if (field === 'inchi') {
        const v = d.inchi.toLowerCase();
        if (v === s) score = 100;
        else if (v.startsWith(s) && s.length >= 8) score = 90;
        else if (v.includes(s) && s.length >= 10) score = 55;
      } else if (field === 'pubchem' || field === 'chebi') {
        const v = (field === 'pubchem' ? d.pubchem : d.chebi).toLowerCase();
        if (v === s) score = 100;
        else if (v.includes(s) && s.length >= 2) score = 55;
      }
      if (score) out.push({ d, score });
    }
    out.sort((a, b) => b.score - a.score || b.d.rels.length - a.d.rels.length);
    return out;
  }

