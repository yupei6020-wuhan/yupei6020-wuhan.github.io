    function walk(node, depth, a0, a1, chain, baseColor) {
      if (depth >= SUN_RINGS.length) return;
      const [r0, r1] = SUN_RINGS[depth];
      const span = a1 - a0;
      const isLeaf = !node.c || !node.c.length;
      const color = depth === 0 ? baseColor : mix(baseColor, 0.1 + depth * 0.1);
      const gap = Math.min(0.006, span * 0.06);
      parts.push('<path class="sun-path' + (isLeaf ? ' leaf' : '') + '" d="' +
        arcPath(CX, CY, r0, r1, a0 + gap, Math.max(a0 + gap + 0.001, a1 - gap)) +
        '" fill="' + color + '" data-id="' + esc(node.id) + '" data-n="' + node.n +
        '" data-chain="' + esc(chain) + '" data-depth="' + depth + '"></path>');

      if (depth === 0 && span > 0.2) {
        const mid = (a0 + a1) / 2, rr = (r0 + r1) / 2;
        parts.push('<text x="' + (CX + rr * Math.cos(mid)).toFixed(1) + '" y="' +
          (CY + rr * Math.sin(mid)).toFixed(1) +
          '" fill="#fff" font-size="12" font-weight="600" text-anchor="middle" ' +
          'dominant-baseline="central" pointer-events="none">' + esc(node.id) + '</text>');
      }

      const kids = node.c || [];
      if (!kids.length) return;
      let a = a0;
      for (const kid of kids) {
        const kSpan = kid.n / node.n * span;
        walk(kid, depth + 1, a, a + kSpan, chain + ' ' + kid.id, baseColor);
        a += kSpan;
      }
    }

