  function arcPath(cx, cy, r0, r1, a0, a1) {
    const p = (r, a) => [cx + r * Math.cos(a), cy + r * Math.sin(a)];
    const large = a1 - a0 > Math.PI ? 1 : 0;
    const A = p(r1, a0), B = p(r1, a1), C = p(r0, a1), E = p(r0, a0);
    return 'M' + A[0].toFixed(2) + ',' + A[1].toFixed(2) +
      'A' + r1 + ',' + r1 + ' 0 ' + large + ' 1 ' + B[0].toFixed(2) + ',' + B[1].toFixed(2) +
      'L' + C[0].toFixed(2) + ',' + C[1].toFixed(2) +
      'A' + r0 + ',' + r0 + ' 0 ' + large + ' 0 ' + E[0].toFixed(2) + ',' + E[1].toFixed(2) + 'Z';
  }

  function mix(hex, t) {
    const n = parseInt(hex.slice(1), 16);
    const r = (n >> 16) & 255, g = (n >> 8) & 255, b = n & 255;
    const m = v => Math.round(v + (255 - v) * t);
    return 'rgb(' + m(r) + ',' + m(g) + ',' + m(b) + ')';
  }

