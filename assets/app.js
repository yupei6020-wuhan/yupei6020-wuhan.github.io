  /* ---------- associations (shared) ---------- */
  function rowFilter(r, state) {
    if (state.onlyEq && isNA(EQ[r[3]])) return false;
    if (state.src.size && !state.src.has(r[2])) return false;
    if (!state.text) return true;
    const t = state.text;
    return ECS[r[0]].toLowerCase().includes(t) || STD[r[1]].toLowerCase().includes(t) ||
      ECN[r[4]].toLowerCase().includes(t) || EQ[r[3]].toLowerCase().includes(t) ||
      SRC[r[2]].toLowerCase().includes(t) || RID[r[5]].toLowerCase().includes(t);
  }

  function scoreText(rows) {
    let mn = 99, mx = -1;
    for (const r of rows) { if (r[15] < mn) mn = r[15]; if (r[15] > mx) mx = r[15]; }
    return mn === mx ? 'Score <b>' + mx + '</b>' : 'Score <b>' + mn + '–' + mx + '</b>';
  }

  function bindAssoc(drug, ecIdx) {
    const state = { src: new Set(), onlyEq: false, text: '' };
    const pairsEl = document.getElementById('pairs');
    const countEl = document.getElementById('assoc-count');
    const toolbar = document.getElementById('assoc-toolbar');

    // list of {d, r}
    let all = [];
    if (drug) {
      all = drug.rels.map(r => ({ d: drug, r }));
    } else {
      for (const d of ecIndex.get(ecIdx).drugs) {
        for (const r of d.rels) if (r[0] === ecIdx) all.push({ d, r });
      }
      all.sort((a, b) => b.d.rels.length - a.d.rels.length || a.d.name.localeCompare(b.d.name));
    }

    const srcCounts = new Map();
    for (const { r } of all) srcCounts.set(r[2], (srcCounts.get(r[2]) || 0) + 1);

    toolbar.innerHTML =
      '<div class="chips" role="group" aria-label="Filter by source">' +
        [...srcCounts.entries()].sort((a, b) => b[1] - a[1]).map(([i, n]) =>
          '<button class="chip" data-src="' + i + '" aria-pressed="false">' +
          '<i style="background:' + SRC_COLOR[i % SRC_COLOR.length] + '"></i>' + esc(SRC[i]) +
          '<span class="n">' + n + '</span></button>').join('') +
      '</div>' +
      '<div class="tools">' +
        '<label class="check"><input type="checkbox" id="only-eq"> With equation</label>' +
        '<input type="search" id="assoc-filter" placeholder="' +
          (drug ? 'Filter EC, name or equation' : 'Filter drug or equation') + '" aria-label="Filter associations">' +
        '<button class="btn ghost sm" id="export" type="button">Export CSV</button>' +
      '</div>';

    function paint() {
      const rows = all.filter(({ r }) => rowFilter(r, state));
      const ecs = new Set(rows.map(({ r }) => r[0]));
      const drugSet = new Set(rows.map(({ d }) => d.id));
      if (drug) {
        countEl.textContent = rows.length === all.length
          ? pl(all.length, 'association') + ' · ' + pl(ecs.size, 'enzyme')
          : pl(rows.length, 'association') + ' of ' + nf(all.length) + ' · ' + pl(ecs.size, 'enzyme');
      } else {
        countEl.textContent = rows.length === all.length
          ? pl(drugSet.size, 'drug') + ' · ' + pl(all.length, 'association')
          : pl(drugSet.size, 'drug') + ' · ' + pl(rows.length, 'association') + ' of ' + nf(all.length);
      }

      if (!rows.length) {
        pairsEl.innerHTML = '<div class="empty"><b>No matching associations</b>Adjust the filters to see more.</div>';
        return;
      }

      const groups = new Map();
      for (const x of rows) {
        const key = drug ? x.r[0] : x.d.id;
        if (!groups.has(key)) groups.set(key, []);
        groups.get(key).push(x);
      }
      const keys = [...groups.keys()].sort((a, b) => {
        if (!drug) return 0;
        return a - b;
      });

      pairsEl.innerHTML = keys.map(k => {
        const list = groups.get(k);
        let head;
        if (drug) {
          const r0 = list[0].r;
          head = '<a class="ec" href="#/ec/' + encodeURIComponent(ECS[k]) + '">' + esc(ECS[k]) + '</a>' +
            '<span class="nm">' + esc(STD[r0[1]]) + '</span>' +
            (r0[9] && r0[9] !== 4 ? '<span class="tag">EC ' + r0[9] + '</span>' : '');
        } else {
          head = '<a class="nm" href="#/drug/' + encodeURIComponent(k) + '">' + esc(list[0].d.name) + '</a>' +
            '<span class="tag">' + esc(k) + '</span>';
        }
        // one row per source; all distinct equations for that source are listed under it
        const bySrc = new Map();
        for (const x of list) {
          if (!bySrc.has(x.r[2])) bySrc.set(x.r[2], []);
          bySrc.get(x.r[2]).push(x.r);
        }
        const body = [...bySrc.entries()]
          .sort((a, b) => b[1].length - a[1].length || a[0] - b[0])
          .map(([si, rs]) => {
            const eqs = rs.sort((a, b) => a[3] - b[3])
              .map(r => '<span class="eq">' + eqCell(EQ[r[3]]) + '</span>').join('');
            return '<li class="row">' + srcTag(si) +
              '<span class="eqs">' + eqs + '</span>' +
              '<span class="score" title="Evidence score (0–8)">' + scoreText(rs) + '</span></li>';
          }).join('');

        return '<div class="pair"><div class="pair-h">' + head + '</div>' +
          '<ul class="rows">' + body + '</ul></div>';
      }).join('');
    }

    toolbar.querySelectorAll('.chip').forEach(chip => {
      chip.addEventListener('click', () => {
        const i = Number(chip.dataset.src);
        const on = chip.getAttribute('aria-pressed') === 'true';
        chip.setAttribute('aria-pressed', String(!on));
        if (on) state.src.delete(i); else state.src.add(i);
        paint();
      });
    });

    let timer;
    document.getElementById('assoc-filter').addEventListener('input', ev => {
      clearTimeout(timer);
      timer = setTimeout(() => { state.text = ev.target.value.trim().toLowerCase(); paint(); }, 120);
    });
    document.getElementById('only-eq').addEventListener('change', ev => {
      state.onlyEq = ev.target.checked;
      paint();
    });
    document.getElementById('export').addEventListener('click', () => {
      exportCSV(all.filter(({ r }) => rowFilter(r, state)), drug ? drug.id : ECS[ecIdx]);
    });

    paint();
  }

