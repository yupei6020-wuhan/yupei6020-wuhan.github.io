  /* ---------- export ---------- */
  const CSV_HEAD = ['drugbank_id', 'name', 'EC', 'EC_standard_name', 'EC_level', 'source', 'EC_name',
    'equation', 'reaction_id', 'substrate_name', 'substrate_id', 'products_name',
    'Score_1', 'Score_2', 'Score_3', 'Score_4', 'BaseScore'];

  function csvCell(v) {
    const s = String(v == null ? '' : v);
    return /[",\n\r]/.test(s) ? '"' + s.replace(/"/g, '""') + '"' : s;
  }

  function exportCSV(items, tag) {
    const rows = items.map(({ d, r }) => [
      d.id, d.name, ECS[r[0]], STD[r[1]], r[9] || 'NA', SRC[r[2]], ECN[r[4]], EQ[r[3]],
      RID[r[5]], SUB[r[6]], SID[r[7]], PRD[r[8]],
      r[11], r[12], r[13], r[14], r[15]
    ]);
    const text = [CSV_HEAD.join(',')].concat(rows.map(r => r.map(csvCell).join(','))).join('\r\n');
    const blob = new Blob(['\ufeff' + text], { type: 'text/csv;charset=utf-8;' });
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob);
    a.download = 'DrugEnz_' + tag + '.csv';
    document.body.appendChild(a); a.click();
    setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 400);
  }

